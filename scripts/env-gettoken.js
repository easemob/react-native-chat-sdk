#!/usr/bin/env node

/**
 * 用法: yarn env:gettoken（零参数）
 *
 * - example/config.local.json 不存在 → 写入占位模板并退出。
 *   该文件被 git 忽略，手工填入真实配置后重跑本脚本。
 * - 存在 → 遍历所有集群：先用 clientId/clientSecret 取 App Token，
 *   再逐个账号用 grant_type=inherit 取 User Token（autoCreateUser=true），
 *   最后把「配置 + token」整体写成 example/src/env.ts.<cluster>。
 *   脚本无状态：不落任何中间缓存，每次全量重取、整文件重写。
 *
 * 激活某个集群: yarn env:use <cluster>（见 scripts/env-use.js）。
 */

const fs = require('node:fs');
const path = require('node:path');

const projectRoot = path.resolve(__dirname, '..');
const configFile = path.join(projectRoot, 'example', 'config.local.json');
const envDir = path.join(projectRoot, 'example', 'src');

const CONFIG_TEMPLATE = {
  _comment:
    '本文件被 git 忽略，存放本地敏感配置。修改后运行 yarn env:gettoken 重新生成 env.ts.<cluster>。可选字段: tokenTtl（user token 有效期秒数，缺省由服务端决定）、pushInfo（{sendId, keyId}）。accounts/groups 条目缺省 cluster 时归到 defaultCluster。',
  defaultCluster: 'ebs',
  clusters: {
    ebs: {
      restApi: 'TODO',
      appKey: 'TODO(orgName#appName)',
      clientId: 'TODO',
      clientSecret: 'TODO',
    },
    ngi: {
      restApi: 'TODO',
      appKey: 'TODO',
      clientId: 'TODO',
      clientSecret: 'TODO',
    },
  },
  accounts: [
    { id: 'TODO-user1', cluster: 'ebs' },
    { id: 'TODO-user2', cluster: 'ebs' },
  ],
  groups: [{ id: 'TODO', owner: 'TODO-user1', name: 'TODO' }],
  chatOptions: {},
};

function isPlaceholder(v) {
  return typeof v !== 'string' || v.length === 0 || v.startsWith('TODO');
}

async function postJson(url, body, bearerToken) {
  const headers = {
    'Content-Type': 'application/json',
    Accept: 'application/json',
  };
  if (bearerToken != null) {
    headers.Authorization = `Bearer ${bearerToken}`;
  }
  const res = await fetch(url, {
    method: 'POST',
    headers,
    body: JSON.stringify(body),
  });
  const text = await res.text();
  let json;
  try {
    json = JSON.parse(text);
  } catch {
    throw new Error(`HTTP ${res.status}: ${text.slice(0, 200)}`);
  }
  if (res.status !== 200) {
    throw new Error(
      `HTTP ${res.status}: ${json.error ?? ''} ${json.error_description ?? ''}`.trim()
    );
  }
  return json;
}

function parseAppKey(appKey) {
  const parts = String(appKey).split('#');
  if (parts.length !== 2 || parts[0] === '' || parts[1] === '') {
    throw new Error(`invalid appKey (expect orgName#appName): ${appKey}`);
  }
  return { orgName: parts[0], appName: parts[1] };
}

async function fetchAppToken(cluster) {
  const { orgName, appName } = parseAppKey(cluster.appKey);
  const url = `${cluster.restApi}/${orgName}/${appName}/token`;
  const json = await postJson(url, {
    grant_type: 'client_credentials',
    client_id: cluster.clientId,
    client_secret: cluster.clientSecret,
  });
  if (typeof json.access_token !== 'string') {
    throw new Error('app token response missing access_token');
  }
  return json.access_token;
}

async function fetchUserToken(cluster, appToken, userId, ttl) {
  const { orgName, appName } = parseAppKey(cluster.appKey);
  const url = `${cluster.restApi}/${orgName}/${appName}/token`;
  const body = { username: userId, grant_type: 'inherit', autoCreateUser: true };
  if (typeof ttl === 'number') {
    body.ttl = ttl;
  }
  const json = await postJson(url, body, appToken);
  if (typeof json.access_token !== 'string') {
    throw new Error('user token response missing access_token');
  }
  return json.access_token;
}

function renderEnvTs(clusterName, cluster, config, accounts) {
  const v = (value) => JSON.stringify(value);
  const generatedAt = new Date().toISOString();
  const groups = (config.groups ?? [])
    .filter(
      (g) =>
        g.cluster == null || g.cluster === clusterName
    )
    .map((g) => {
      const { cluster: _cluster, ...rest } = g;
      return rest;
    });
  const pushInfo = config.pushInfo ?? {};
  const lines = [
    `// Generated by scripts/env-gettoken.js from example/config.local.json`,
    `// cluster: ${clusterName}  generated: ${generatedAt}`,
    `// DO NOT EDIT — 手改请改 example/config.local.json 后重跑 yarn env:gettoken`,
    `// 激活本集群: yarn env:use ${clusterName}`,
    `export const test = true;`,
    `export const appKey = [${v(cluster.appKey ?? '')}];`,
    `export const appId = [${v(cluster.appId ?? '')}];`,
    `export const PushInfo = { sendId: ${v(pushInfo.sendId)}, KeyId: ${v(
      pushInfo.keyId
    )} };`,
    `export const accounts = ${v(accounts)};`,
    `export const groups = ${v(groups)};`,
    `export const webSocketServers = ${v(cluster.webSocketServers ?? [])};`,
    `export const restServers = ${v(cluster.restServers ?? [cluster.restApi])};`,
    `export const msyncServers = ${v(cluster.msyncServers ?? [])};`,
  ];
  // chatOptions 扩展位: 键值平铺为顶层导出，auto 模式的 CHAT_OPTIONS_KEYS 可直接消费
  for (const [key, value] of Object.entries(config.chatOptions ?? {})) {
    lines.push(`export const ${key} = ${v(value)};`);
  }
  return lines.join('\n') + '\n';
}

async function main() {
  if (fs.existsSync(configFile) === false) {
    fs.writeFileSync(
      configFile,
      JSON.stringify(CONFIG_TEMPLATE, null, 2) + '\n',
      'utf-8'
    );
    console.log(`${configFile} created.`);
    console.log(
      '请填写各集群的 restApi/appKey/clientId/clientSecret 和 accounts 后重跑 yarn env:gettoken'
    );
    return;
  }

  const config = JSON.parse(fs.readFileSync(configFile, 'utf-8'));
  const clusters = config.clusters ?? {};
  const defaultCluster = config.defaultCluster;
  const ttl = config.tokenTtl;

  let failed = 0;
  for (const [clusterName, cluster] of Object.entries(clusters)) {
    const clusterAccounts = (config.accounts ?? []).filter(
      (a) => (a.cluster ?? defaultCluster) === clusterName
    );
    if (
      isPlaceholder(cluster.restApi) ||
      isPlaceholder(cluster.appKey) ||
      isPlaceholder(cluster.clientId) ||
      isPlaceholder(cluster.clientSecret)
    ) {
      console.log(`[${clusterName}] 配置未填写完整，跳过`);
      continue;
    }
    console.log(
      `[${clusterName}] 获取 app token，共 ${clusterAccounts.length} 个账号`
    );
    let appToken;
    try {
      appToken = await fetchAppToken(cluster);
    } catch (e) {
      console.error(`[${clusterName}] app token 失败: ${e.message}`);
      failed += 1;
      continue;
    }
    const accounts = [];
    for (const account of clusterAccounts) {
      try {
        const token = await fetchUserToken(cluster, appToken, account.id, ttl);
        accounts.push({ id: account.id, mm: token });
        console.log(`[${clusterName}] ${account.id} ok`);
      } catch (e) {
        accounts.push({ id: account.id, mm: '' });
        console.error(`[${clusterName}] ${account.id} 失败: ${e.message}`);
        failed += 1;
      }
    }
    const envFile = path.join(envDir, `env.ts.${clusterName}`);
    fs.writeFileSync(
      envFile,
      renderEnvTs(clusterName, cluster, config, accounts),
      'utf-8'
    );
    console.log(`[${clusterName}] ${envFile} generated`);
  }
  if (failed > 0) {
    process.exitCode = 1;
  }
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
