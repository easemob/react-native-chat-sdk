#!/usr/bin/env node

/**
 * 用法: yarn env:gettoken（零参数）
 *
 * 本项目只配置「当前这一个环境」：example/config.local.json 描述它，
 * 换环境＝直接改/换这个文件。需要在多套环境间切换时，可自行在 Git 外
 * 维护 config.ngi.json / config.ebs.json 这类副本（不入库，敏感信息由
 * 使用者人工管理），用哪套就把它复制为 config.local.json。
 *
 * - example/config.local.json 不存在 → 写入占位模板并退出。
 *   该文件被 git 忽略，手工填入真实配置后重跑本脚本。
 * - 存在 → 用 clientId/clientSecret 取 App Token，再逐个账号用
 *   grant_type=inherit 取 User Token（autoCreateUser=true），最后把
 *   「配置 + token」整体写成 example/src/env.ts。
 *   脚本无状态：不落任何中间缓存，每次全量重取、整文件重写。
 */

const fs = require('node:fs');
const path = require('node:path');

const projectRoot = path.resolve(__dirname, '..');
const configFile = path.join(projectRoot, 'example', 'config.local.json');
const envFile = path.join(projectRoot, 'example', 'src', 'env.ts');

const CONFIG_TEMPLATE = {
  _comment:
    '本文件被 git 忽略，存放当前这一个环境的敏感配置与测试数据，修改后运行 yarn env:gettoken 重新生成 env.ts。换环境＝直接改/换本文件；如需多套环境，可自行在 Git 外维护 config.ngi.json / config.ebs.json 这类副本（不入库，敏感信息人工管理）。可选字段: tokenTtl（user token 有效期秒数，缺省由服务端决定）、pushInfo（{sendId, keyId}）。chatOptions 对应 SDK 的 ChatOptions，平铺为 env.ts 顶层导出（键见 example/src/auto/auto_mode.ts 的 CHAT_OPTIONS_KEYS）。enablePrivateConfig 为私有化部署开关，缺省 false（公有环境，webSocketServer/restServer/msyncServer 不生成）；置 true 时三个私有化参数生成进 env.ts（TODO/空值跳过）。',
  restApi: 'TODO',
  appKey: 'TODO(orgName#appName)',
  clientId: 'TODO',
  clientSecret: 'TODO',
  accounts: [{ id: 'TODO-user1' }, { id: 'TODO-user2' }],
  groups: [{ id: 'TODO', owner: 'TODO-user1', name: 'TODO' }],
  chatOptions: {},
  enablePrivateConfig: false,
  webSocketServer: 'TODO',
  restServer: 'TODO',
  msyncServer: 'TODO',
};

function isPlaceholder(v) {
  return typeof v !== 'string' || v.length === 0 || v.startsWith('TODO');
}

async function postJson(url, body, bearerToken) {
  const headers = {
    'Content-Type': 'application/json',
    Accept: 'application/json',
  };
  if (bearerToken != null) {
    headers.Authorization = `Bearer ${bearerToken}`;
  }
  const res = await fetch(url, {
    method: 'POST',
    headers,
    body: JSON.stringify(body),
  });
  const text = await res.text();
  let json;
  try {
    json = JSON.parse(text);
  } catch {
    throw new Error(`HTTP ${res.status}: ${text.slice(0, 200)}`);
  }
  if (res.status !== 200) {
    throw new Error(
      `HTTP ${res.status}: ${json.error ?? ''} ${json.error_description ?? ''}`.trim()
    );
  }
  return json;
}

function parseAppKey(appKey) {
  const parts = String(appKey).split('#');
  if (parts.length !== 2 || parts[0] === '' || parts[1] === '') {
    throw new Error(`invalid appKey (expect orgName#appName): ${appKey}`);
  }
  return { orgName: parts[0], appName: parts[1] };
}

async function fetchAppToken(config) {
  const { orgName, appName } = parseAppKey(config.appKey);
  const url = `${config.restApi}/${orgName}/${appName}/token`;
  const json = await postJson(url, {
    grant_type: 'client_credentials',
    client_id: config.clientId,
    client_secret: config.clientSecret,
  });
  if (typeof json.access_token !== 'string') {
    throw new Error('app token response missing access_token');
  }
  return json.access_token;
}

async function fetchUserToken(config, appToken, userId, ttl) {
  const { orgName, appName } = parseAppKey(config.appKey);
  const url = `${config.restApi}/${orgName}/${appName}/token`;
  const body = { username: userId, grant_type: 'inherit', autoCreateUser: true };
  if (typeof ttl === 'number') {
    body.ttl = ttl;
  }
  const json = await postJson(url, body, appToken);
  if (typeof json.access_token !== 'string') {
    throw new Error('user token response missing access_token');
  }
  return json.access_token;
}

function renderEnvTs(config, accounts) {
  const v = (value) => JSON.stringify(value);
  const generatedAt = new Date().toISOString();
  const groups = (config.groups ?? []).map((g) => {
    const { cluster: _cluster, ...rest } = g;
    return rest;
  });
  const pushInfo = config.pushInfo ?? {};
  const lines = [
    `// Generated by scripts/env-gettoken.js from example/config.local.json`,
    `// generated: ${generatedAt}`,
    `// DO NOT EDIT — 手改请改 example/config.local.json 后重跑 yarn env:gettoken`,
    `export const test = true;`,
    `export const appKey = [${v(config.appKey ?? '')}];`,
    `export const appId = [${v(config.appId ?? '')}];`,
    `export const PushInfo = { sendId: ${v(pushInfo.sendId)}, KeyId: ${v(
      pushInfo.keyId
    )} };`,
    `export const accounts = ${v(accounts)};`,
    `export const groups = ${v(groups)};`,
  ];
  // chatOptions 对应 SDK 的 ChatOptions，键值平铺为顶层导出，
  // auto 模式的 CHAT_OPTIONS_KEYS 可直接消费。
  for (const [key, value] of Object.entries(config.chatOptions ?? {})) {
    lines.push(`export const ${key} = ${v(value)};`);
  }
  // 私有化部署配置: enablePrivateConfig 为公私切换开关，缺省 false（公有环境，
  // 三个参数不生成）；置 true 时 webSocketServer/restServer/msyncServer 生成进
  // env.ts（TODO 占位或空值跳过）。
  if (config.enablePrivateConfig === true) {
    for (const key of ['webSocketServer', 'restServer', 'msyncServer']) {
      if (!isPlaceholder(config[key])) {
        lines.push(`export const ${key} = ${v(config[key])};`);
      }
    }
  }
  return lines.join('\n') + '\n';
}

async function main() {
  if (fs.existsSync(configFile) === false) {
    fs.writeFileSync(
      configFile,
      JSON.stringify(CONFIG_TEMPLATE, null, 2) + '\n',
      'utf-8'
    );
    console.log(`${configFile} created.`);
    console.log(
      '请填写该环境的 restApi/appKey/clientId/clientSecret 和 accounts 后重跑 yarn env:gettoken'
    );
    return;
  }

  const config = JSON.parse(fs.readFileSync(configFile, 'utf-8'));
  if (config.clusters != null || config.defaultCluster != null) {
    throw new Error(
      'example/config.local.json 仍是已移除的多集群格式（clusters/defaultCluster）；' +
        '请把当前环境的 restApi/appKey/clientId/clientSecret 移到顶层后重跑 yarn env:gettoken'
    );
  }
  for (const key of ['restApi', 'appKey', 'clientId', 'clientSecret']) {
    if (isPlaceholder(config[key])) {
      throw new Error(`example/config.local.json 缺少必填字段: ${key}`);
    }
  }

  // accounts/groups 条目里遗留的 cluster 键静默丢弃（兼容从旧格式粘贴的配置）。
  const accountIds = (config.accounts ?? []).map((a) => a.id);
  if (accountIds.some((id) => isPlaceholder(id))) {
    throw new Error('example/config.local.json 的 accounts 存在未填写的 id');
  }

  console.log(`获取 app token，共 ${accountIds.length} 个账号`);
  const appToken = await fetchAppToken(config);
  const accounts = [];
  for (const id of accountIds) {
    const token = await fetchUserToken(config, appToken, id, config.tokenTtl);
    accounts.push({ id, mm: token });
    console.log(`${id} ok`);
  }

  fs.writeFileSync(envFile, renderEnvTs(config, accounts), 'utf-8');
  console.log(`${envFile} generated`);
}

main().catch((e) => {
  console.error(e.message ?? e);
  process.exitCode = 1;
});
